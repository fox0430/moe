proc utfFold*(r: Rune): Rune =
  ## Vim's utf_fold(): `r` as 'ignorecase' compares it.
  if r.int32 < 0x80:
    if r.int32 >= 0x41 and r.int32 <= 0x5a:
      Rune(r.int32 + 32)
    else:
      r
  else:
    r.convert(FoldCase)

proc utfIsUpper*(r: Rune): bool =
  ## Vim's utf_isupper(), with its default 'casemap'.
  if r.int32 < 0x80:
    r.int32 >= 0x41 and r.int32 <= 0x5a
  else:
    r.convert(ToLower) != r
