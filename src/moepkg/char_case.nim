## Vim's case tables, which 'ignorecase' and 'smartcase' go by.

import std/unicode

type CaseRange = tuple[first, last, step, offset: int32]

proc convert(r: Rune, table: openArray[CaseRange]): Rune =
  ## Vim's utf_convert().
  let c = r.int32
  var
    start = 0
    stop = table.len
  while start < stop:
    let mid = (start + stop) div 2
    if table[mid].last < c:
      start = mid + 1
    else:
      stop = mid
  if start < table.len and table[start].first <= c and c <= table[start].last and
      (c - table[start].first) mod table[start].step == 0:
    Rune(c + table[start].offset)
  else:
    r

