proc latin1Class(c: int): int =
  ## Vim's class below 0x100, by its default 'iskeyword' (`@,48-57,_,192-255`).
  ## A NUL in the text is punctuation, as Vim keeps it as a line feed.
  case c
  of 0x09, 0x20, 0xa0:
    0
  of '0'.ord .. '9'.ord,
      'A'.ord .. 'Z'.ord,
      '_'.ord,
      'a'.ord .. 'z'.ord,
      0xb5, # µ, the one letter of 0x80..0xbf with a case
      0xc0 .. 0xff:
    2
  else:
    1

proc rangeIndex[T](table: openArray[T], c: int32): int =
  ## The index of the range of the sorted `table` that holds `c`, or -1.
  var
    lo = 0
    hi = table.len - 1
  while lo <= hi:
    let mid = (lo + hi) div 2
    if table[mid][1] < c:
      lo = mid + 1
    elif table[mid][0] > c:
      hi = mid - 1
    else:
      return mid
  -1

proc utfClass*(r: Rune): int =
  ## Vim's utf_class(): 0 for a blank, 1 for punctuation and 2 or more for a
  ## class of word characters (3 for emoji, 0x4e00 for CJK ideographs,
  ## 0x3040 for Hiragana...). An undecodable byte is classed as the byte, as
  ## Vim reads it.
  if r.isInvalidByteRune:
    return latin1Class(r.invalidByteValue.int)
  let c = r.int32
  if c < 0x100:
    return latin1Class(c)
  if EmojiAll.rangeIndex(c) >= 0:
    return 3
  let i = UtfClasses.rangeIndex(c)
  if i >= 0:
    UtfClasses[i][2].int
  else:
    2 # Most other characters are word characters

proc mbClass*(r: Rune): int =
  ## Vim's mb_get_class(): utf_class(), but an undecodable byte that Vim reads
  ## alone goes by 'iskeyword', so 0xa0 is no blank there.
  if r.isInvalidByteRune and r.invalidByteValue == 0xa0:
    1
  else:
    utfClass(r)

proc isComposing*(r: Rune): bool =
  ## Vim's utf_iscomposing(): a character drawn over the one before it, which
  ## Vim takes as part of that one.
  r.int32 >= 0x300 and Combining.rangeIndex(r.int32) >= 0

proc baseColumn*(runes: openArray[Rune], column: int): int =
  ## The column of the character the one at `column` is part of: a composing
  ## character's is the one before it. One that starts the line or follows an
  ## undecodable byte stands alone, as in Vim's utfc_ptr2len().
  result = column
  while result > 0 and runes[result].isComposing and
      not runes[result - 1].isInvalidByteRune:
    dec result

proc isVimWhite*(r: Rune): bool =
  ## Vim's VIM_ISWHITE: a space or a tab only.
  r == Rune(' ') or r == Rune('\t')

proc isVimSpace*(r: Rune): bool =
  ## Vim's vim_isspace(): a space or a character from tab to carriage return.
  ## A NUL in the text is one, as Vim keeps it as a line feed.
  r == Rune(' ') or r.int == 0 or (r.int >= 0x09 and r.int <= 0x0d)
