type FoldJoin* = enum
  ## Which rows an edit adds below a fold's last line go into the fold, as
  ## Vim's foldMarkAdjust in Insert.
  fjNone ## None, as an edit not typed or a put in Normal mode
  fjTyped ## One row, as a line break typed or a put in Insert
  fjPasted ## Any number, as Vim types a paste line by line
