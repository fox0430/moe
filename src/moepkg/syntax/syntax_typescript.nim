## TypeScript tokenizer. Lexing is shared with JavaScript in `syntax_jslike`;
## this module is the TypeScript-mode entry point.

import tokenizer, syntax_jslike

const
  typescriptBooleans* = jsBooleans
  typescriptBuiltins* = jsBuiltins
  typescriptKeywords* = tsKeywords

proc tsGetKeyword*(id: string): TokenClass =
  jsLikeGetKeyword(id, tsMode = true)

proc typescriptNextToken*(g: var GeneralTokenizer) =
  jsLikeNextToken(g, tsMode = true)
