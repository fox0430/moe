# Regenerates tools/test_shards.txt from the compile times in a CI log.
# Usage: gh run view <unit tests run id> --log | nim r tools/gen_test_shards.nim [shards]

import std/[algorithm, os, sequtils, strutils, tables]

import ./paralleltest

const
  DefaultShards = 4
  # Runs in the lsp-e2e job, so no shard ever logs it.
  UnshardedTests = ["test_lsp_e2e_lasm.nim"]
  # A sequential test holds a whole runner, not one of its parallel jobs.
  SequentialWeightFactor = 4.0

proc parseCompileTimes(input: File): Table[string, float] =
  # A compile logs two SuccessX lines, front end and then total; keep the total.
  for line in input.lines:
    if not line.startsWith("shard ") or "[SuccessX]" notin line:
      continue
    let parts = line.split("; ")
    let proj = parts.filterIt(it.startsWith("proj: "))
    if parts.len < 2 or proj.len != 1:
      continue
    let path = proj[0].substr("proj: ".len)
    if path.parentDir.lastPathPart != "tests":
      continue
    let
      file = path.extractFilename
      seconds = parseFloat(parts[1].strip(chars = {'s'}))
    if seconds > result.getOrDefault(file):
      result[file] = seconds

proc parseShardCount(): int =
  if paramCount() < 1:
    return DefaultShards
  try:
    result = parseInt(paramStr(1))
  except ValueError:
    result = 0
  if result < 1:
    quit("Shard count must be a positive integer (got " & paramStr(1) & ")", 1)

proc main() =
  let shards = parseShardCount()

  var weights: seq[tuple[weight: float, file: string]]
  let compileTimes = parseCompileTimes(stdin)
  if compileTimes.len == 0:
    quit("No compile times found on stdin", 1)

  let missing = discoverTestFiles()
    .filterIt(it notin compileTimes and it notin UnshardedTests)
    .sorted()
  if missing.len > 0:
    quit(
      "Log is incomplete, " & ShardTableFile & " left unchanged. Missing: " &
        missing.join(", "),
      1,
    )

  for file, seconds in compileTimes:
    if fileExists("tests" / file):
      let factor = if file in SequentialTests: SequentialWeightFactor else: 1.0
      weights.add((seconds * factor, file))
  weights.sort(Descending)

  var
    loads = newSeq[float](shards)
    assigned: seq[tuple[file: string, shard: int, weight: float]]
  for (weight, file) in weights:
    let lightest = loads.find(loads.min())
    loads[lightest] += weight
    assigned.add((file, lightest + 1, weight))
  assigned.sort(
    proc(a, b: auto): int =
      cmp(a.file, b.file)
  )

  var output =
    "# Generated by tools/gen_test_shards.nim. Columns: test file, shard, weight.\n" &
    ShardCountPrefix & $shards & "\n"
  for (file, shard, weight) in assigned:
    output.add file & " " & $shard & " " & weight.formatFloat(ffDecimal, 1) & "\n"
  writeFile(ShardTableFile, output)

  echo "Wrote ", assigned.len, " tests to ", ShardTableFile
  for i, load in loads:
    echo "  shard ", i + 1, ": ", load.int

main()
